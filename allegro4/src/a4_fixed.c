const fixed fixtorad_r = 1608;      /* 2pi/256 in 16.16 */
const fixed radtofix_r = 2670177;   /* 256/2pi in 16.16 */

fixed fixsin(fixed x)
{
    uint32_t a = (uint32_t)x & 0xFFFFFF;    /* 256 units a turn: 24 bits */
    uint32_t quadrant = a >> 22, pos = a & 0x3FFFFF;   /* 64 units a quadrant */
    uint32_t idx, frac;
    int32_t v;
    if (quadrant & 1) pos = 0x400000 - pos;
    idx = pos >> 14;                        /* 0..256 */
    frac = pos & 0x3FFF;
    if (idx >= 256) v = quarter_sin[256];
    else v = quarter_sin[idx] + (int32_t)(((int64_t)(quarter_sin[idx + 1] - quarter_sin[idx]) * frac) >> 14);
    return (quadrant & 2) ? -v : v;
}

fixed fixcos(fixed x) { return fixsin(x + itofix(64)); }

fixed fixtan(fixed x)
{
    fixed c = fixcos(x);
    return fixdiv(fixsin(x), c);
}

fixed fixatan(fixed x)
{
    int neg = x < 0;
    uint32_t ax = (uint32_t)(neg ? -x : x);
    fixed r;
    if (ax <= 0x10000) {
        uint32_t idx = ax >> 8, frac = ax & 0xFF;
        r = idx >= 256 ? atan_tab[256] : atan_tab[idx] + (int32_t)(((int64_t)(atan_tab[idx + 1] - atan_tab[idx]) * frac) >> 8);
    } else {
        /* atan(x) = 64 - atan(1/x) */
        r = itofix(64) - fixatan(fixdiv(0x10000, (fixed)ax));
    }
    return neg ? -r : r;
}

fixed fixatan2(fixed y, fixed x)
{
    fixed r;
    if (x == 0) {
        if (y == 0) return 0;
        return y > 0 ? itofix(64) : -itofix(64);
    }
    r = fixatan(fixdiv(y, x));
    if (x < 0) r += (y >= 0) ? itofix(128) : -itofix(128);
    return r;
}

fixed fixsqrt(fixed x)
{
    uint64_t v, res = 0, bit;
    if (x <= 0) return 0;
    v = (uint64_t)(uint32_t)x << 16;
    bit = (uint64_t)1 << 46;
    while (bit > v) bit >>= 2;
    while (bit) {
        if (v >= res + bit) { v -= res + bit; res = (res >> 1) + bit; }
        else res >>= 1;
        bit >>= 2;
    }
    return (fixed)res;
}

fixed fixhypot(fixed x, fixed y)
{
    int64_t s = (int64_t)x * x + (int64_t)y * y;     /* 32.32 */
    uint64_t v = (uint64_t)s, res = 0, bit = (uint64_t)1 << 62;
    while (bit > v) bit >>= 2;
    while (bit) {
        if (v >= res + bit) { v -= res + bit; res = (res >> 1) + bit; }
        else res >>= 1;
        bit >>= 2;
    }
    return (fixed)res;
}
